"""Generate deterministic type stub packages from cached schemas."""

import datetime
import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path

from sgalchemy._core._registry import entity_reserved_attribute_names
from sgalchemy._errors import SgalchemyError
from sgalchemy._stubgen_registry import render_registry_stub
from sgalchemy.schema import _aliases, _model
from sgalchemy.schema._cache import SchemaCache

_HASH_PREFIX = '# sgalchemy-stubs schema-hash: '
_IMAGE_READ_TYPE = 'str | os.PathLike[str] | os.PathLike[bytes] | None'
_IMAGE_WRITE_TYPES = {
    'image': 'str | os.PathLike[str] | os.PathLike[bytes] | None',
    'filmstrip_image': 'str | os.PathLike[str] | os.PathLike[bytes]',
}


@dataclass(frozen=True)
class StubReport:
    """Result of generating one complete stub package.

    Attributes:
        written: Paths to generated stub files.
        skipped_aliases: Reports for aliases that could not be generated.
    """

    written: list[Path]
    skipped_aliases: list[str]
    _hash: str


def _header(digest: str) -> str:
    """Render the shared generated-file header."""
    return f'# Generated by sgalchemy; do not edit.\n{_HASH_PREFIX}{digest}\n'


def _render_python_type(python_type: type) -> str:
    """Render a schema Python type as a stub annotation."""
    if python_type is datetime.date:
        return 'datetime.date'
    if python_type is datetime.datetime:
        return 'datetime.datetime'
    if python_type is dict:
        return 'dict[str, Any]'
    if python_type is list:
        return 'list[Any]'
    return python_type.__name__


def _render_field_type(
    field: _model.FieldSchema,
    schemas: dict[str, _model.EntitySchema],
) -> tuple[str, str | None]:
    """Render a field value annotation and its optional entity import."""
    if field.code in _IMAGE_WRITE_TYPES:
        return _IMAGE_READ_TYPE, None
    if field.data_type in {'entity', 'multi_entity'}:
        target = field.valid_types[0] if len(field.valid_types) == 1 else None
        target = target if target in schemas else None
        annotation = target or 'Entity'
        if field.data_type == 'multi_entity':
            return f'list[{annotation}]', target  # LIVE-PIN: no links is `[]` on the wire.
        return f'{annotation} | None', target
    return f'{_render_python_type(field.python_type)} | None', None


def _render_types_stub(header: str) -> str:
    """Render the shared dual-role field descriptor stub."""
    return (
        f'{header}\n'
        'from typing import Generic, TypeVar, overload\n'
        '\n'
        'from sgalchemy import Entity, FieldExpr\n'
        '\n'
        "_ReadT_co = TypeVar('_ReadT_co', covariant=True)\n"
        "_WriteT_contra = TypeVar('_WriteT_contra', contravariant=True)\n"
        '\n'
        '\n'
        'class _SGField(Generic[_ReadT_co, _WriteT_contra]):\n'
        '    @overload\n'
        '    def __get__(self, obj: None, owner: type) -> FieldExpr: ...\n'
        '    @overload\n'
        '    def __get__(self, obj: Entity, owner: type) -> _ReadT_co: ...\n'
        '    def __set__(self, obj: Entity, value: _WriteT_contra) -> None: ...\n'
    )


def _render_write_type(field: _model.FieldSchema, read_type: str) -> str:
    """Render the statically supported field assignment type."""
    if field.code == 'id' or (field.data_type == 'image' and field.code not in _IMAGE_WRITE_TYPES):
        return 'Never'
    return _IMAGE_WRITE_TYPES.get(field.code, read_type)


def _render_annotations(
    schema: _model.EntitySchema,
    schemas: dict[str, _model.EntitySchema],
    *,
    include_field_aliases: bool,
) -> tuple[list[tuple[str, str, str]], set[str], list[str]]:
    """Render entity annotations, imports, and skipped-alias reports."""
    annotations: list[tuple[str, str, str]] = []
    referenced_types: set[str] = set()
    skipped_aliases: list[str] = []
    for code in schema.readable_field_codes():
        field = schema.fields[code]
        annotation, target = _render_field_type(field, schemas)
        annotations.append((code, annotation, _render_write_type(field, annotation)))
        if target is not None and target != schema.type_name:
            referenced_types.add(target)

    if include_field_aliases:
        aliases, skipped_aliases = _aliases.field_aliases(
            schema,
            reserved_names=entity_reserved_attribute_names(),
        )
        for alias, code in sorted(aliases.items()):
            field = schema.fields[code]
            if not field.api_readable:
                continue
            annotation, target = _render_field_type(field, schemas)
            annotations.append((alias, annotation, _render_write_type(field, annotation)))
            if target is not None and target != schema.type_name:
                referenced_types.add(target)
    return annotations, referenced_types, skipped_aliases


def _schema_hash(
    cache: SchemaCache,
    *,
    entity_aliases: bool = True,
    field_aliases: bool = True,
    permissive: bool = False,
) -> str:
    """Hash schema content that affects generated stubs."""
    payload = {
        'entities': cache.entities,
        'entity_aliases': entity_aliases,
        'fields': cache.fields,
        'field_aliases': field_aliases,
        'permissive': permissive,
    }
    serialized = json.dumps(payload, sort_keys=True)
    return hashlib.sha256(serialized.encode(), usedforsecurity=False).hexdigest()


def _snake_type_name(type_name: str) -> str:
    """Convert one CapWords entity type name to snake case."""
    with_word_boundaries = re.sub(r'(.)([A-Z][a-z]+)', r'\1_\2', type_name)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', with_word_boundaries).lower()


def _entity_paths(cache: SchemaCache, entities_dir: Path) -> dict[str, Path]:
    """Map entity types to distinct generated stub paths."""
    entity_paths: dict[str, Path] = {}
    path_owners: dict[Path, str] = {}
    for type_name in cache.fields:
        path = entities_dir / f'_{_snake_type_name(type_name)}.pyi'
        if path in path_owners:
            owner = path_owners[path]
            raise SgalchemyError(
                f'entity types {owner!r} and {type_name!r} map to the same '
                f'generated stub path: {path}'
            )
        entity_paths[type_name] = path
        path_owners[path] = type_name
    return entity_paths


def _render_entity_stub(
    header: str,
    schema: _model.EntitySchema,
    schemas: dict[str, _model.EntitySchema],
    *,
    include_field_aliases: bool,
    permissive: bool,
) -> tuple[str, list[str]]:
    """Render one entity stub and its skipped-alias reports."""
    annotations, referenced_types, skipped_aliases = _render_annotations(
        schema,
        schemas,
        include_field_aliases=include_field_aliases,
    )
    needs_any = permissive or any(
        'Any' in read_type or 'Any' in write_type for _, read_type, write_type in annotations
    )
    imports: list[str] = []
    if any(
        'datetime.' in read_type or 'datetime.' in write_type
        for _, read_type, write_type in annotations
    ):
        imports.append('import datetime')
    if any('os.PathLike' in write_type for _, _, write_type in annotations):
        imports.append('import os')
    if needs_any:
        imports.append('from typing import Any')
    if any(write_type == 'Never' for _, _, write_type in annotations):
        imports.append('from typing import Never')
    if imports:
        imports.append('')
    imports.append('from sgalchemy import Entity')
    imports.extend(
        f'from sgalchemy.entities._{_snake_type_name(target)} import {target}'
        for target in sorted(referenced_types)
    )
    imports.append('from sgalchemy.entities._types import _SGField')

    body = [f'class {schema.type_name}(Entity):']
    body.extend(
        f'    {name}: _SGField[{read_type}, {write_type}]'
        for name, read_type, write_type in annotations
    )
    if permissive:
        body.append('    def __getattr__(self, name: str) -> Any: ...')
    if len(body) == 1:
        body.append('    ...')
    return (
        f'{header}\n' + '\n'.join(imports) + '\n\n\n' + '\n'.join(body) + '\n',
        skipped_aliases,
    )


def _render_init_stub(
    header: str,
    schemas: dict[str, _model.EntitySchema],
    aliases: dict[str, str],
) -> str:
    """Render the generated entity package initializer stub."""
    lines = [
        (
            f'from sgalchemy.entities._{_snake_type_name(type_name)} '
            f'import {type_name} as {type_name}'
        )
        for type_name in sorted(schemas)
    ]
    if aliases:
        lines.append('')
        lines.extend(f'{alias} = {target}' for alias, target in sorted(aliases.items()))
    return f'{header}\n' + '\n'.join(lines) + '\n'


def _render_stubs(
    cache: SchemaCache,
    entities_dir: Path,
    *,
    entity_aliases: bool,
    field_aliases: bool,
    permissive: bool,
) -> tuple[dict[Path, str], list[str], str]:
    """Render one complete deterministic stub package without writing it."""
    digest = _schema_hash(
        cache,
        entity_aliases=entity_aliases,
        field_aliases=field_aliases,
        permissive=permissive,
    )
    schemas = _model.build_schema(cache)
    entity_paths = _entity_paths(cache, entities_dir)

    aliases: dict[str, str] = {}
    skipped_aliases: list[str] = []
    if entity_aliases:
        aliases, skipped_aliases = _aliases.entity_aliases(schemas)

    header = _header(digest)
    rendered: dict[Path, str] = {
        entities_dir / '__init__.pyi': _render_init_stub(header, schemas, aliases),
        entities_dir / '_types.pyi': _render_types_stub(header),
        entities_dir.parent / '_core' / '_registry.pyi': render_registry_stub(
            header, permissive=permissive
        ),
    }
    for type_name, schema in sorted(schemas.items()):
        text, field_reports = _render_entity_stub(
            header,
            schema,
            schemas,
            include_field_aliases=field_aliases,
            permissive=permissive,
        )
        rendered[entity_paths[type_name]] = text
        skipped_aliases.extend(field_reports)
    return rendered, skipped_aliases, digest


def check_stubs(
    cache: SchemaCache,
    out: Path,
    *,
    entity_aliases: bool = True,
    field_aliases: bool = True,
    permissive: bool = False,
) -> bool:
    """Return whether a complete generated stub package matches a schema.

    Args:
        cache: Current schema snapshot.
        out: Root directory containing the generated `sgalchemy` package.
        entity_aliases: Whether display-name entity aliases are expected.
        field_aliases: Whether stripped `sg_` field aliases are expected.
        permissive: Whether generated classes should accept unknown attributes.

    Returns:
        True when every expected entity and registry stub matches the rendered
        tree byte for byte, with no obsolete entity stubs. Read or render
        failures return False.
    """
    entities_dir = out / 'sgalchemy' / 'entities'
    try:
        rendered, _skipped_aliases, _digest = _render_stubs(
            cache,
            entities_dir,
            entity_aliases=entity_aliases,
            field_aliases=field_aliases,
            permissive=permissive,
        )
        owned = set(entities_dir.rglob('*.pyi'))
        companion = entities_dir.parent / '_core' / '_registry.pyi'
        if companion.is_file():
            owned.add(companion)
        if not entities_dir.is_dir() or owned != set(rendered):
            return False
        return all(path.read_bytes() == text.encode('utf-8') for path, text in rendered.items())
    except (OSError, SgalchemyError):
        return False


def generate_stubs(
    cache: SchemaCache,
    out: Path,
    *,
    entity_aliases: bool = True,
    field_aliases: bool = True,
    permissive: bool = False,
) -> StubReport:
    """Generate a complete deterministic entity stub package.

    Generation owns every `.pyi` beneath `out/sgalchemy/entities` and the
    `out/sgalchemy/_core/_registry.pyi` companion. It removes obsolete entity
    stubs and overwrites current generated files, preserving other `_core`
    files.

    Args:
        cache: Schema snapshot used to generate entity annotations.
        out: Root directory under which to create the `sgalchemy` package.
        entity_aliases: Whether to emit display-name entity aliases.
        field_aliases: Whether to emit stripped `sg_` field aliases.
        permissive: Whether generated classes accept unknown attributes as
            `Any`.

    Returns:
        A report of paths written and skipped aliases.

    Raises:
        SgalchemyError: If entity types map to the same generated stub path.
        OSError: If generated files cannot be created, removed, or written.
    """
    entities_dir = out / 'sgalchemy' / 'entities'
    rendered, skipped_aliases, digest = _render_stubs(
        cache,
        entities_dir,
        entity_aliases=entity_aliases,
        field_aliases=field_aliases,
        permissive=permissive,
    )
    expected = set(rendered)
    entities_dir.mkdir(parents=True, exist_ok=True)
    for obsolete in set(entities_dir.rglob('*.pyi')) - expected:
        obsolete.unlink()

    written = sorted(rendered)
    for path in written:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(rendered[path].encode('utf-8'))
    return StubReport(written=written, skipped_aliases=skipped_aliases, _hash=digest)
